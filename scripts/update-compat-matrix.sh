# Auto-update the Stellar protocol compatibility matrix. (#273)
#
# Updates docs/compatibility.md with the latest testnet protocol version
# and last-tested date, then commits the change via the GitHub Actions bot.
#
# Usage:
#   ./scripts/update-compat-matrix.sh <protocol_version>
#
# Environment variables:
#   GITHUB_TOKEN — GitHub token for committing (set by Actions)
#   GIT_AUTHOR_NAME, GIT_AUTHOR_EMAIL — optional override for commit identity
set -euo pipefail

PROTOCOL_VERSION="${1:-}"

if [[ -z "$PROTOCOL_VERSION" ]]; then
  echo "Error: protocol version argument is required" >&2
  echo "Usage: $0 <protocol_version>" >&2
  exit 1
fi

COMPAT_FILE="docs/compatibility.md"

if [[ ! -f "$COMPAT_FILE" ]]; then
  echo "Error: $COMPAT_FILE not found" >&2
  exit 1
fi

# Get current date in ISO format
CURRENT_DATE=$(date -u +"%Y-%m-%d")

echo "Updating compatibility matrix with protocol version $PROTOCOL_VERSION (tested $CURRENT_DATE)"

# Update the "Stellar Testnet (current protocol)" line in the testing section
# to reflect the latest tested protocol version and date.
if grep -q "Last tested against testnet protocol" "$COMPAT_FILE"; then
  sed -i "s/Last tested against testnet protocol.*$/Last tested against testnet protocol $PROTOCOL_VERSION ($CURRENT_DATE)/" "$COMPAT_FILE"
else
  # Insert a line after the "Stellar Testnet (current protocol)" bullet
  sed -i "/Stellar Testnet (current protocol)/a - Last tested against testnet protocol $PROTOCOL_VERSION ($CURRENT_DATE)" "$COMPAT_FILE"
fi

# Update the SDK and Tooling Requirements table — update the "Tested" column
# for soroban-sdk and Stellar CLI rows with the current date if the protocol
# version changed.
if grep -q "Last verified:" "$COMPAT_FILE"; then
  sed -i "s/Last verified:.*$/Last verified: $CURRENT_DATE (protocol $PROTOCOL_VERSION)/" "$COMPAT_FILE"
else
  # Add a "Last verified" note at the end of the Testing section
  sed -i "/Reporting Compatibility Issues/i - Last verified: $CURRENT_DATE (protocol $PROTOCOL_VERSION)" "$COMPAT_FILE"
fi

# Configure git for the bot commit
git config user.name "github-actions[bot]"
git config user.email "github-actions[bot]@users.noreply.github.com"

# Stage and commit the update
git add "$COMPAT_FILE"

if git diff --cached --quiet; then
  echo "No changes to compatibility matrix — already up to date."
  exit 0
fi

git commit -m "docs: update compatibility matrix — protocol $PROTOCOL_VERSION ($CURRENT_DATE)

Auto-generated by weekly-testnet-smoke job in stellar-protocol-compat.yml (#273).

[skip ci]"

echo "Compatibility matrix updated and committed."
